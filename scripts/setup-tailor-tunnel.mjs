#!/usr/bin/env node
/**
 * One-time setup: named Cloudflare Tunnel → localhost:8787
 * Uses wrangler OAuth token. Writes .env.tailor + scripts/cloudflared-tailor.yml
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const ACCOUNT_ID = "a4e4f5c1214af712b0f5f48ef7c722ec";
const TUNNEL_NAME = "atriveo-tailor";
const ZONE_NAME = "atriveo.com";
const OPTIONAL_HOSTNAME = "tailor-relay.atriveo.com";

function readWranglerToken() {
  const cfg = path.join(os.homedir(), "Library/Preferences/.wrangler/config/default.toml");
  const text = fs.readFileSync(cfg, "utf8");
  const m = text.match(/oauth_token\s*=\s*"([^"]+)"/);
  if (!m) throw new Error("wrangler oauth_token not found — run: npx wrangler login");
  return m[1];
}

async function cf(token, method, apiPath, body) {
  const res = await fetch(`https://api.cloudflare.com/client/v4${apiPath}`, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const data = await res.json();
  if (!data.success) {
    throw new Error(`${method} ${apiPath}: ${JSON.stringify(data.errors || data)}`);
  }
  return data.result;
}

function mergeEnvTailor(updates) {
  const envPath = path.join(ROOT, ".env.tailor");
  const lines = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8").split("\n") : [];
  const map = new Map();
  for (const line of lines) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i > 0) map.set(t.slice(0, i), t.slice(i + 1));
  }
  for (const [k, v] of Object.entries(updates)) map.set(k, v);
  const out = [...map.entries()].map(([k, v]) => `${k}=${v}`).join("\n") + "\n";
  fs.writeFileSync(envPath, out);
}

async function main() {
  const token = readWranglerToken();
  console.log("→ Cloudflare account", ACCOUNT_ID);

  let tunnels = await cf(token, "GET", `/accounts/${ACCOUNT_ID}/cfd_tunnel?name=${TUNNEL_NAME}`);
  let tunnel = tunnels.find((t) => t.name === TUNNEL_NAME);
  if (!tunnel) {
    const secret = Buffer.from(cryptoRandom(32)).toString("base64");
    tunnel = await cf(token, "POST", `/accounts/${ACCOUNT_ID}/cfd_tunnel`, {
      name: TUNNEL_NAME,
      tunnel_secret: secret,
      config_src: "cloudflare",
    });
    console.log("→ Created tunnel", tunnel.id);
  } else {
    console.log("→ Reusing tunnel", tunnel.id);
  }

  await cf(token, "PUT", `/accounts/${ACCOUNT_ID}/cfd_tunnel/${tunnel.id}/configurations`, {
    config: {
      ingress: [
        { hostname: OPTIONAL_HOSTNAME, service: "http://127.0.0.1:8787" },
        { service: "http_status:404" },
      ],
    },
  });
  const origin = `https://${OPTIONAL_HOSTNAME}`;
  console.log("→ Ingress", OPTIONAL_HOSTNAME, "→ 127.0.0.1:8787");

  const zones = await cf(token, "GET", `/zones?name=${ZONE_NAME}`);
  const zone = zones[0];
  const cname = `${tunnel.id}.cfargotunnel.com`;
  let dnsOk = false;
  if (zone) {
    try {
      const records = await cf(token, "GET", `/zones/${zone.id}/dns_records?name=${OPTIONAL_HOSTNAME}`);
      if (!records.length) {
        await cf(token, "POST", `/zones/${zone.id}/dns_records`, {
          type: "CNAME",
          name: "tailor-relay",
          content: cname,
          proxied: true,
        });
        console.log("→ Optional DNS CNAME", OPTIONAL_HOSTNAME, "→", cname);
      } else {
        console.log("→ Optional DNS already exists for", OPTIONAL_HOSTNAME);
      }
      dnsOk = true;
    } catch {
      console.warn("→ Optional pretty hostname skipped (OAuth cannot edit DNS). Using cfargotunnel.com URL.");
    }
  }

  const runToken = await cf(token, "GET", `/accounts/${ACCOUNT_ID}/cfd_tunnel/${tunnel.id}/token`);

  fs.writeFileSync(
    path.join(ROOT, "scripts/cloudflared-tailor.yml"),
    `# Auto-generated by scripts/setup-tailor-tunnel.mjs — do not commit\n# Run: cloudflared tunnel run --token $CLOUDFLARED_TUNNEL_TOKEN\n`,
  );

  mergeEnvTailor({
    CLOUDFLARED_TUNNEL_TOKEN: runToken,
    TAILOR_ORIGIN: origin,
  });

  console.log("→ Setting TAILOR_ORIGIN on Cloudflare Pages…");
  const wr = spawnSync(
    "npx",
    ["wrangler", "pages", "secret", "put", "TAILOR_ORIGIN", "--project-name", "atriveo-app"],
    { cwd: ROOT, input: origin, encoding: "utf8" },
  );
  if (wr.status !== 0) {
    console.error(wr.stderr || wr.stdout);
    throw new Error("wrangler pages secret put TAILOR_ORIGIN failed");
  }

  console.log("\n✓ Tailor tunnel ready");
  console.log("  TAILOR_ORIGIN:", origin);
  if (!dnsOk) {
    console.log("\n  DNS required for permanent relay. Run once:");
    console.log("    cloudflared tunnel login");
    console.log("    npm run tailor:dns");
    console.log(`    (CNAME tailor-relay → ${cname})`);
    console.log("\n  Then install auto-start:");
    console.log("    npm run tailor:install");
  } else {
    console.log("  Install auto-start: npm run tailor:install");
  }
}

function cryptoRandom(n) {
  const b = new Uint8Array(n);
  crypto.getRandomValues(b);
  return b;
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
